DEFAULTS = {
    "institute_name": "GVTIW Samanabad, Faisalabad",
    "shift_start": "08:00",
    "shift_end": "14:30",
    "grace_minutes": "10",
    "weekly_off": "Sunday",
    "ingest_key": "",
}


def _translate_pg(sql: str) -> str:
    """Rewrite the few SQLite-isms in our SQL into Postgres equivalents."""
    s = sql.replace("?", "%s")
    if s.lstrip().upper().startswith("INSERT OR IGNORE INTO"):
        s = "INSERT INTO" + s[len("INSERT OR IGNORE INTO"):] + " ON CONFLICT DO NOTHING"
    elif s.lstrip().upper().startswith("INSERT OR REPLACE INTO HOLIDAYS"):
        s = ("INSERT INTO holidays(date, name) VALUES(%s, %s) "
             "ON CONFLICT(date) DO UPDATE SET name=EXCLUDED.name")
    return s


class Conn:
    """Thin wrapper so the rest of the app uses one API on both backends."""

    def __init__(self, raw, pg: bool):
        self._raw = raw
        self.pg = pg

    def execute(self, sql: str, params: tuple = ()):
        if self.pg:
            cur = self._raw.cursor()
            cur.execute(_translate_pg(sql), params)
            return cur
        return self._raw.execute(sql, params)

    def executescript(self, script: str) -> None:
        if self.pg:
            cur = self._raw.cursor()
            for stmt in script.split(";"):
                if stmt.strip():
                    cur.execute(stmt)
        else:
            self._raw.executescript(script)

    def commit(self) -> None:
        self._raw.commit()

    def close(self) -> None:
        self._raw.close()


def connect() -> Conn:
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row
        return Conn(psycopg.connect(DATABASE_URL, row_factory=dict_row), pg=True)
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    raw = sqlite3.connect(str(DB_PATH))
    raw.row_factory = sqlite3.Row
    raw.execute("PRAGMA journal_mode=WAL")
    return Conn(raw, pg=False)


def init_db() -> None:
    conn = connect()
    try:
        conn.executescript(PG_SCHEMA if conn.pg else SQLITE_SCHEMA)
        # migration for databases created before staff.device_sn existed
        if conn.pg:
            conn.execute("ALTER TABLE staff ADD COLUMN IF NOT EXISTS device_sn TEXT DEFAULT ''")
        else:
            try:
                conn.execute("ALTER TABLE staff ADD COLUMN device_sn TEXT DEFAULT ''")
            except Exception:
                pass
        for k, v in DEFAULTS.items():
            conn.execute("INSERT OR IGNORE INTO settings(key, value) VALUES(?, ?)", (k, v))
        if not get_setting(conn, "ingest_key"):
            set_setting(conn, "ingest_key", secrets.token_urlsafe(24))
        conn.commit()
    finally:
        conn.close()


def get_setting(conn: Conn, key: str, default: str = "") -> str:
    row = conn.execute("SELECT value FROM settings WHERE key=?", (key,)).fetchone()
    return row["value"] if row else default


def set_setting(conn: Conn, key: str, value: str) -> None:
    conn.execute("INSERT INTO settings(key, value) VALUES(?, ?) "
                 "ON CONFLICT(key) DO UPDATE SET value=excluded.value", (key, value))


def hash_password(password: str, salt: str | None = None) -> str:
    salt = salt or secrets.token_hex(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt.encode(), 200_000).hex()
    return f"{salt}${digest}"


def verify_password(password: str, stored: str) -> bool:
    try:
        salt, digest = stored.split("$", 1)
    except ValueError:
        return False
    return secrets.compare_digest(hash_password(password, salt), stored)


def create_session(conn: Conn, ttl_hours: float = 72) -> str:
    token = secrets.token_urlsafe(32)
    conn.execute("INSERT INTO sessions(token, expires_at) VALUES(?, ?)",
                 (token, time.time() + ttl_hours * 3600))
    conn.execute("DELETE FROM sessions WHERE expires_at < ?", (time.time(),))
    conn.commit()
    return token


def valid_session(conn: Conn, token: str | None) -> bool:
    if not token:
        return False
    row = conn.execute("SELECT expires_at FROM sessions WHERE token=?", (token,)).fetchone()
    return bool(row and row["expires_at"] > time.time())


def destroy_session(conn: Conn, token: str) -> None:
    conn.execute("DELETE FROM sessions WHERE token=?", (token,))
    conn.commit()
